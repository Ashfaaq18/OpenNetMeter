using System.Globalization;
using System.Text.RegularExpressions;
using OpenNetMeter.Services;

namespace OpenNetMeter.Tests;

public class HtmlReportTests
{
    [Theory]
    [InlineData("<script>alert(1)</script>", "&lt;script&gt;alert(1)&lt;/script&gt;")]
    [InlineData("\"><img src=x onerror=alert(1)>", "&quot;&gt;&lt;img src=x onerror=alert(1)&gt;")]
    [InlineData("Tom & Jerry's", "Tom &amp; Jerry&#39;s")]
    public void Encode_EscapesMarkupCharacters(string input, string expected)
    {
        Assert.Equal(expected, HtmlReport.Encode(input));
    }

    [Theory]
    [InlineData("report.html", true)]
    [InlineData("report.HTML", true)]
    [InlineData("report.htm", true)]
    [InlineData(@"C:\out\report.HTM", true)]
    [InlineData("report.csv", false)]
    [InlineData("report.json", false)]
    [InlineData("report", false)]
    [InlineData("report.html.txt", false)]
    [InlineData("report.htmlx", false)]
    public void IsHtmlPath_MatchesHtmlAndHtmExtensions(string path, bool expected)
    {
        Assert.Equal(expected, HtmlReport.IsHtmlPath(path));
    }

    [Fact]
    public void WriteDocumentStart_DeclaresAStrictContentSecurityPolicy()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteDocumentStart(w, "A <b>title</b>"));

        Assert.StartsWith("<!DOCTYPE html>", html);
        Assert.Contains("<html lang=\"en\">", html);
        Assert.Contains("<meta charset=\"utf-8\">", html);
        Assert.Contains("<meta name=\"viewport\"", html);
        Assert.Contains(
            "<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\">",
            html);
        Assert.Contains("<title>A &lt;b&gt;title&lt;/b&gt;</title>", html);
        Assert.Contains("<h1>A &lt;b&gt;title&lt;/b&gt;</h1>", html);
        Assert.Contains("prefers-color-scheme:dark", html);
        Assert.Contains("@media print", html);
        Assert.Contains(".hint{display:none}", html);
        HtmlTestHelpers.AssertNoActiveOrExternalContent(html);
    }

    [Fact]
    public void WriteDocumentEnd_WritesFooterAndClosesTheDocument()
    {
        var html = HtmlTestHelpers.Render(HtmlReport.WriteDocumentEnd);

        Assert.Matches(@"^<footer>Generated by OpenNetMeter on .+</footer>\n", html);
        Assert.EndsWith("</main>\n</body>\n</html>\n", html);
    }

    [Fact]
    public void WriteMeta_EncodesTextAndColoursTheTotals()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteMeta(w,
        [
            ("Profile", "<b>x</b>"),
            (HtmlReport.TotalDownloadLabel, "1 MB"),
            (HtmlReport.TotalUploadLabel, "2 MB")
        ]));

        Assert.Contains("<dt>Profile</dt><dd>&lt;b&gt;x&lt;/b&gt;</dd>", html);
        Assert.Contains("<dt>Total download</dt><dd class=\"dl\">1 MB</dd>", html);
        Assert.Contains("<dt>Total upload</dt><dd class=\"ul\">2 MB</dd>", html);
    }

    [Fact]
    public void WriteProcessTable_SortsByTotalDescendingThenName()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w,
        [
            ("beta.exe", 10, 0),
            ("Alpha.exe", 5, 5),
            ("small.exe", 1, 0),
            ("gamma.exe", 100, 0)
        ]));

        Assert.Equal(["gamma.exe", "Alpha.exe", "beta.exe", "small.exe"], HtmlTestHelpers.FirstCells(html));
        Assert.Contains("<th>Process</th><th class=\"num\">Download</th><th class=\"num\">Upload</th><th class=\"num\">Total</th><th class=\"share\">Share</th>", html);
    }

    [Fact]
    public void WriteProcessTable_ShareBarsAreRelativeToTheLargestRow()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w,
        [
            ("quarter.exe", 250, 250),
            ("big.exe", 1000, 1000),
            ("idle.exe", 0, 0),
            ("half.exe", 500, 500)
        ]));

        Assert.Equal(["100.0", "50.0", "25.0", "0.0"], HtmlTestHelpers.ShareWidths(html));
        Assert.Contains("<div class=\"track\"><div class=\"fill\" style=\"width:100.0%\"></div></div>", html);
        Assert.Contains("<div class=\"track\"><div class=\"fill\" style=\"width:50.0%\"></div></div>", html);
    }

    [Fact]
    public void WriteProcessTable_OnlyNumbersGoIntoStyleAttributes()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w,
        [
            ("\" style=\"x:y", 3, 0),
            ("other.exe", 1, 0)
        ]));

        var styles = Regex.Matches(html, "style=\"([^\"]*)\"").Select(m => m.Groups[1].Value).ToList();
        Assert.Equal(["width:100.0%", "width:33.3%"], styles);
        Assert.Contains("<td>&quot; style=&quot;x:y</td>", html);
    }

    [Theory]
    [InlineData(1, 3, "33.3")]
    [InlineData(2, 3, "66.7")]
    [InlineData(1, 1, "100.0")]
    [InlineData(0, 100, "0.0")]
    [InlineData(5, 0, "0.0")]
    [InlineData(200, 100, "100.0")]
    [InlineData(-5, 100, "0.0")]
    public void FormatShareWidth_ClampsAndUsesOneDecimal(long total, long max, string expected)
    {
        Assert.Equal(expected, HtmlReport.FormatShareWidth(total, max));
    }

    [Fact]
    public void WriteProcessTable_ShowsReadableSizesWithExactBytesInTheTitle()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w, [("big.exe", 123_456_789, 1_048_576)]));

        Assert.Contains("<td class=\"num\" title=\"123,456,789 bytes\">", html);
        Assert.Contains("<td class=\"num\" title=\"1,048,576 bytes\">1 MB</td>", html);
        Assert.Contains("<td class=\"num\" title=\"124,505,365 bytes\">", html);
    }

    [Fact]
    public void WriteProcessTable_UsesInvariantNumbersWhateverTheCulture()
    {
        var previous = CultureInfo.CurrentCulture;
        CultureInfo.CurrentCulture = new CultureInfo("fr-FR");
        try
        {
            var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w, [("a.exe", 2_000_000, 0), ("b.exe", 1_000_000, 0)]));

            Assert.Contains("title=\"2,000,000 bytes\"", html);
            Assert.Equal(["100.0", "50.0"], HtmlTestHelpers.ShareWidths(html));
        }
        finally
        {
            CultureInfo.CurrentCulture = previous;
        }
    }

    [Fact]
    public void WriteProcessTable_WithoutRowsWritesANoTrafficParagraph()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteProcessTable(w, []));

        Assert.Equal("<p class=\"empty\">No traffic recorded.</p>\n", html);
    }

    [Fact]
    public void WriteDayTable_SortsOldestFirstAndHasNoShareColumn()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteDayTable(w,
        [
            (new DateOnly(2026, 3, 10), 3, 4),
            (new DateOnly(2026, 3, 2), 1, 2)
        ]));

        Assert.Equal(
            [HtmlTestHelpers.Day(2026, 3, 2), HtmlTestHelpers.Day(2026, 3, 10)],
            HtmlTestHelpers.FirstCells(html));
        Assert.Contains("<td class=\"num\" title=\"7 bytes\">7 B</td>", html);
        Assert.DoesNotContain("class=\"track\"", html);
    }

    [Fact]
    public void WriteExpandableProcessTable_SortsByTotalDescendingThenName()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
        [
            Proc("beta.exe", (new DateOnly(2026, 3, 1), 10, 0)),
            Proc("Alpha.exe", (new DateOnly(2026, 3, 1), 5, 5)),
            Proc("small.exe", (new DateOnly(2026, 3, 1), 1, 0)),
            Proc("gamma.exe", (new DateOnly(2026, 3, 1), 100, 0))
        ]));

        Assert.Equal(["gamma.exe", "Alpha.exe", "beta.exe", "small.exe"], HtmlTestHelpers.SummaryNames(html));
        Assert.Contains("<div class=\"prow phead\"><span>Process</span><span class=\"num\">Download</span><span class=\"num\">Upload</span><span class=\"num\">Total</span><span class=\"share\">Share</span></div>", html);
        Assert.Contains("<p class=\"hint\">Click a process to see its usage per day.</p>", html);
        HtmlTestHelpers.AssertNoActiveOrExternalContent(html);
    }

    [Fact]
    public void WriteExpandableProcessTable_ShareBarsAreRelativeToTheLargestRow()
    {
        var day = new DateOnly(2026, 3, 1);
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
        [
            Proc("quarter.exe", (day, 250, 250)),
            Proc("big.exe", (day, 1000, 1000)),
            Proc("half.exe", (day, 500, 500))
        ]));

        Assert.Equal(["100.0", "50.0", "25.0"], HtmlTestHelpers.ShareWidths(html));
        Assert.Contains("<span class=\"share\"><span class=\"track\"><span class=\"fill\" style=\"width:50.0%\"></span></span></span>", html);
    }

    [Fact]
    public void WriteExpandableProcessTable_ExpandsToAscendingDaysAndSkipsDaysWithoutTraffic()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
        [
            Proc("app.exe",
                (new DateOnly(2026, 3, 10), 3, 4),
                (new DateOnly(2026, 3, 5), 0, 0),
                (new DateOnly(2026, 3, 2), 1, 2))
        ]));

        var block = Assert.Single(HtmlTestHelpers.ProcessBlocks(html));
        // The summary carries the whole period: 4 down, 6 up, 10 in total.
        var summary = Regex.Match(block, "<summary class=\"prow\">(.*?)</summary>").Groups[1].Value;
        Assert.Contains("title=\"4 bytes\"", summary);
        Assert.Contains("title=\"6 bytes\"", summary);
        Assert.Contains("title=\"10 bytes\"", summary);

        Assert.Equal([HtmlTestHelpers.Day(2026, 3, 2), HtmlTestHelpers.Day(2026, 3, 10)], HtmlTestHelpers.DayNames(block));
        var firstDay = Regex.Match(block, "<div class=\"prow pday\">(.*?)</div>").Groups[1].Value;
        Assert.Contains("title=\"1 bytes\"", firstDay);
        Assert.Contains("title=\"2 bytes\"", firstDay);
        Assert.Contains("title=\"3 bytes\"", firstDay);
        Assert.Contains("<span></span></div>", block);
    }

    [Fact]
    public void WriteExpandableProcessTable_RowsStartCollapsed()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
            [Proc("app.exe", (new DateOnly(2026, 3, 1), 1, 1))]));

        Assert.Contains("<details class=\"pitem\">", html);
        Assert.DoesNotContain("<details open", html);
        Assert.DoesNotContain(" open>", html);
    }

    [Fact]
    public void WriteExpandableProcessTable_ProcessWithoutDaysIsNotExpandable()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
        [
            ("idle.exe", 0, 0, []),
            Proc("zero-days.exe", (new DateOnly(2026, 3, 1), 0, 0))
        ]));

        Assert.DoesNotContain("<details", html);
        Assert.DoesNotContain("<summary", html);
        Assert.Equal(2, Regex.Matches(html, "<div class=\"prow pstatic\">").Count);
        Assert.Contains("<span class=\"pname\">idle.exe</span>", html);
    }

    [Fact]
    public void WriteExpandableProcessTable_WithoutRowsWritesOnlyANoTrafficParagraph()
    {
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w, []));

        Assert.Equal("<p class=\"empty\">No traffic recorded.</p>\n", html);
    }

    [Fact]
    public void WriteExpandableProcessTable_EncodesNamesAndOnlyNumbersGoIntoStyleAttributes()
    {
        var day = new DateOnly(2026, 3, 1);
        var html = HtmlTestHelpers.Render(w => HtmlReport.WriteExpandableProcessTable(w,
        [
            Proc("\" style=\"x:y", (day, 3, 0)),
            Proc("<script>alert(1)</script>", (day, 1, 0))
        ]));

        var styles = Regex.Matches(html, "style=\"([^\"]*)\"").Select(m => m.Groups[1].Value).ToList();
        Assert.Equal(["width:100.0%", "width:33.3%"], styles);
        Assert.Equal(["&quot; style=&quot;x:y", "&lt;script&gt;alert(1)&lt;/script&gt;"], HtmlTestHelpers.SummaryNames(html));
        HtmlTestHelpers.AssertNoActiveOrExternalContent(html);
    }

    private static (string Process, long Download, long Upload, IReadOnlyList<(DateOnly Date, long Download, long Upload)> Days) Proc(
        string process, params (DateOnly Date, long Download, long Upload)[] days) =>
        (process, days.Sum(d => d.Download), days.Sum(d => d.Upload), days);
}

/// <summary>
/// Shared helpers for the tests that render and inspect the HTML exports.
/// </summary>
internal static class HtmlTestHelpers
{
    // Every tag the reports are allowed to contain; anything else (script, img, a, iframe...) fails the check.
    private static readonly HashSet<string> AllowedTags =
    [
        "html", "head", "meta", "title", "style", "body", "main", "h1", "h2", "h3", "section", "dl", "div",
        "dt", "dd", "table", "thead", "tbody", "tr", "th", "td", "p", "footer", "details", "summary", "span"
    ];

    public const char EnDash = (char)0x2013;

    public static string Render(Action<TextWriter> write)
    {
        var writer = new StringWriter { NewLine = "\n" };
        write(writer);
        return writer.ToString();
    }

    public static string Day(int year, int month, int day) =>
        HtmlReport.Encode(HtmlReport.FormatDate(new DateOnly(year, month, day)));

    /// <summary>The text of the first cell of every body row, in document order.</summary>
    public static List<string> FirstCells(string html) =>
        Regex.Matches(html, "<tr><td>([^<]*)</td>").Select(m => m.Groups[1].Value).ToList();

    /// <summary>The process names of the summary rows of an expandable table, in document order.</summary>
    public static List<string> SummaryNames(string html) =>
        Regex.Matches(html, "<summary class=\"prow\"><span class=\"pname\">([^<]*)</span>").Select(m => m.Groups[1].Value).ToList();

    /// <summary>The date labels of the per-day rows of an expandable table, in document order.</summary>
    public static List<string> DayNames(string html) =>
        Regex.Matches(html, "<div class=\"prow pday\"><span class=\"pname\">([^<]*)</span>").Select(m => m.Groups[1].Value).ToList();

    /// <summary>The inner HTML of every expandable process (<c>details</c>), in document order.</summary>
    public static List<string> ProcessBlocks(string html) =>
        Regex.Matches(html, "<details class=\"pitem\">(.*?)</details>", RegexOptions.Singleline).Select(m => m.Groups[1].Value).ToList();

    /// <summary>The share bar widths (without the percent sign) in document order.</summary>
    public static List<string> ShareWidths(string html) =>
        Regex.Matches(html, "class=\"fill\" style=\"width:([0-9.]+)%\"").Select(m => m.Groups[1].Value).ToList();

    /// <summary>Fails if the page contains any tag outside the allow list, scripts, event handlers or external references.</summary>
    public static void AssertNoActiveOrExternalContent(string html)
    {
        foreach (Match tag in Regex.Matches(html, @"<\s*/?\s*([A-Za-z][A-Za-z0-9]*)"))
            Assert.Contains(tag.Groups[1].Value.ToLowerInvariant(), AllowedTags);

        Assert.DoesNotContain("<script", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("<img", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("<link", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("<iframe", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotMatch(@"(?i)<[^>]*\son[a-z]+\s*=", html);
        Assert.DoesNotContain("http://", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("https://", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("@import", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("url(", html, StringComparison.OrdinalIgnoreCase);
    }
}
